#!/bin/bash
# Validates a commit message subject: "<emoji> <type>[(scope)][!]: <message>"
#   ./scripts/check-commit-msg.sh <file>      (used by the commit-msg hook)
#   ./scripts/check-commit-msg.sh -m "<msg>"  (used by CI)
# Allowed pairs are listed in CONTRIBUTING.md. Emoji and type must match.
set -u

ALLOWED="✨ feat
🐛 fix
📝 docs
💄 style
♻️ refactor
⚡️ perf
✅ test
👷 ci
🔧 chore
🔒 security
🔖 release
⏪ revert"

if [ "${1:-}" = "-m" ]; then
  msg="${2:-}"
else
  [ -f "${1:-}" ] || { echo "usage: $0 <commit-msg-file> | -m <message>" >&2; exit 2; }
  msg="$(cat "$1")"
fi

subject="$(printf '%s\n' "$msg" | grep -v '^#' | sed '/^[[:space:]]*$/d' | head -1)"

# Merge/revert commits generated by git or GitHub are allowed as-is.
case "$subject" in
  "Merge "*|"Revert \""*) exit 0 ;;
esac

strip_vs16() { sed $'s/\xef\xb8\x8f//g'; }  # treat ♻ and ♻️ alike
norm="$(printf '%s' "$subject" | strip_vs16)"

while IFS= read -r pair; do
  p="$(printf '%s' "$pair" | strip_vs16)"
  case "$norm" in
    "$p: "?*|"$p!: "?*|"$p("*"): "?*|"$p("*")!: "?*)
      scope_ok=1
      case "$norm" in
        "$p("*) printf '%s' "$norm" | grep -Eq '^[^(]+\([a-z0-9._/-]+\)!?: ' || scope_ok=0 ;;
      esac
      [ "$scope_ok" = 1 ] && exit 0
      ;;
  esac
done <<EOF
$ALLOWED
EOF

{
  echo "✗ Invalid commit message:"
  echo "    $subject"
  echo
  echo "  Required format:  <emoji> <type>[(scope)]: <message>"
  echo "  Example:          ✨ feat: add --color option"
  echo
  echo "  Allowed emoji/type pairs:"
  printf '%s\n' "$ALLOWED" | sed 's/^/    /'
} >&2
exit 1
